import { z } from 'zod'

export const DownloadOptionsSchema = z.object({
  kind: z.enum(['video', 'audio']),
  quality: z.union([
    z.literal(480),
    z.literal(720),
    z.literal(1080),
    z.literal(1440),
    z.literal(2160),
  ]),
  container: z.enum(['mp4', 'mkv']),
  audioFormat: z.enum(['mp3', 'm4a', 'wav']),
  bitrate: z.union([z.literal(128), z.literal(256), z.literal(320)]),
  embedMetadata: z.boolean(),
  videoFormatId: z.string().optional(),
  audioFormatId: z.string().optional(),
})

export const AppErrorSchema = z.object({
  code: z.enum([
    'CANCELED',
    'DISK_FULL',
    'ENGINE_BAD_ARCH',
    'ENGINE_NOT_FOUND',
    'ENGINE_UPDATE_FAILED',
    'EXTERNAL_URL_BLOCKED',
    'FFMPEG_FAILED',
    'FFMPEG_MISSING',
    'FILENAME_TOO_LONG',
    'FORMAT_UNAVAILABLE',
    'GEO_BLOCKED',
    'HTTP_403_OR_BLOCKED',
    'INVALID_REQUEST',
    'INVALID_URL',
    'LIVE_NOT_SUPPORTED',
    'LOGIN_REQUIRED',
    'NETWORK_OFFLINE',
    'NETWORK_STALLED',
    'PERMISSION_DENIED',
    'SYSTEM_ACTION_FAILED',
    'UNKNOWN',
    'UNSUPPORTED_URL',
    'VIDEO_UNAVAILABLE',
  ]),
  message: z.string(),
  detail: z.string().optional(),
  retryable: z.boolean(),
  hint: z.string().optional(),
})

export const DownloadJobSchema = z.object({
  id: z.uuid(),
  url: z.string(),
  mediaId: z.string(),
  title: z.string(),
  uploader: z.string().optional(),
  thumbnailUrl: z.string().optional(),
  platform: z.string(),
  durationSec: z.number().optional(),
  options: DownloadOptionsSchema,
  outputDir: z.string(),
  state: z.enum([
    'queued',
    'starting',
    'downloading',
    'processing',
    'paused',
    'completed',
    'failed',
    'canceled',
  ]),
  progress: z.object({
    percent: z.number().optional(),
    downloadedBytes: z.number().optional(),
    totalBytes: z.number().optional(),
    speedBps: z.number().optional(),
    etaSec: z.number().optional(),
    phase: z.enum(['queued', 'downloading', 'merging', 'converting', 'finalizing', 'completed']),
  }),
  filePath: z.string().optional(),
  error: AppErrorSchema.optional(),
  createdAt: z.string(),
  startedAt: z.string().optional(),
  finishedAt: z.string().optional(),
  attempt: z.number().int().nonnegative(),
  stallRetries: z.number().int().nonnegative(),
  usedContainerFallback: z.boolean(),
  usedGenericFallback: z.boolean().default(false),
})

export const HistoryItemSchema = z.object({
  id: z.uuid(),
  url: z.string(),
  title: z.string(),
  uploader: z.string().optional(),
  thumbnailUrl: z.string().optional(),
  platform: z.string(),
  options: DownloadOptionsSchema,
  filePath: z.string(),
  fileSize: z.number().nonnegative(),
  durationSec: z.number().optional(),
  completedAt: z.string(),
})
